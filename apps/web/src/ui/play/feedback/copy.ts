export const feedbackEnglish:Record<string,string> = Object.fromEntries(Object.entries(en).map(([key,value])=>[`fb.${key}`,value]));
export const feedbackPortuguese:Record<string,string> = Object.fromEntries(Object.entries(pt).map(([key,value])=>[`fb.${key}`,value]));

/** Turn feedback, report and journal copy; falls back to English until the tables are registered. */
export function useFeedbackCopy() {
  const {t} = useTranslation();
  return (key: string, values?: Record<string, string | number>) => t(`fb.${key}`, {...values, defaultValue: (en as Record<string,string>)[key] ?? key});
}
