export type QuizFilter = 'all' | QuizTopic;
/** Questions in their authored order, optionally limited to one topic. */
export function questionsFor(filter: QuizFilter): readonly QuizQuestion[] {
  return filter === 'all' ? QUIZ_QUESTIONS : QUIZ_QUESTIONS.filter(question => question.topic === filter);
}
/** Counts answered and correct questions among `questions`; unanswered questions are neither. */
export function quizScore(questions: readonly QuizQuestion[], answers: Readonly<Record<string, number>>): { answered: number; correct: number; total: number } {
  let answered = 0, correct = 0;
  for (const question of questions) {
    const choice = answers[question.id];
    if (choice === undefined) continue;
    answered++;
    if (choice === question.answer) correct++;
  }
  return { answered, correct, total: questions.length };
}
